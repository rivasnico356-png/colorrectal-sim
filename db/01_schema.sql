-- Colorrectal-Sim · Esquema PostgreSQL 16 (modelo físico v1.0, 19 tablas)
-- Fuente: 1.3.2.5 Arquitectura de datos v1.0 (Medical programmers).
-- Sin datos personales ni secretos. Se ejecuta automáticamente al crear el contenedor de la base de datos.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

BEGIN;

-- Catálogo de roles: Usuario, Profesional de la salud y Administrador.
CREATE TABLE rol (
    id_rol                    SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre                    VARCHAR(30) NOT NULL UNIQUE,
    CONSTRAINT pk_rol PRIMARY KEY (id_rol)
);

-- Niveles de gamificación por puntaje mínimo.
CREATE TABLE nivel (
    id_nivel                  SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre                    VARCHAR(40) NOT NULL UNIQUE,
    puntaje_minimo            INTEGER NOT NULL,
    CONSTRAINT pk_nivel PRIMARY KEY (id_nivel)
);

-- Cuenta de toda persona que usa la plataforma; el rol define sus permisos.
CREATE TABLE usuario (
    id_usuario                UUID DEFAULT gen_random_uuid(),
    id_rol                    SMALLINT NOT NULL,
    id_nivel                  SMALLINT,
    nombre                    VARCHAR(120) NOT NULL,
    correo                    VARCHAR(160) NOT NULL UNIQUE,
    hash_contrasena           VARCHAR(255) NOT NULL,
    rango_edad                VARCHAR(20) NOT NULL,
    puntaje_acumulado         INTEGER DEFAULT 0 NOT NULL,
    estado                    VARCHAR(12) DEFAULT 'activo' NOT NULL,
    intentos_fallidos         SMALLINT DEFAULT 0 NOT NULL,
    bloqueado_hasta           TIMESTAMPTZ,
    fecha_registro            TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES rol (id_rol),
    CONSTRAINT fk_usuario_nivel FOREIGN KEY (id_nivel) REFERENCES nivel (id_nivel),
    CONSTRAINT ck_usuario_1 CHECK (estado IN ('activo','inactivo')),
    CONSTRAINT ck_usuario_2 CHECK (intentos_fallidos >= 0),
    CONSTRAINT ck_usuario_3 CHECK (puntaje_acumulado >= 0)
);

-- Autorizaciones de tratamiento de datos otorgadas o revocadas (Ley 1581 de 2012).
CREATE TABLE autorizacion_datos (
    id_autorizacion           BIGINT GENERATED ALWAYS AS IDENTITY,
    id_usuario                UUID NOT NULL,
    tipo                      VARCHAR(30) NOT NULL,
    version_politica          VARCHAR(10) NOT NULL,
    aceptada                  BOOLEAN DEFAULT FALSE NOT NULL,
    fecha_aceptacion          TIMESTAMPTZ,
    fecha_revocacion          TIMESTAMPTZ,
    CONSTRAINT pk_autorizacion_datos PRIMARY KEY (id_autorizacion),
    CONSTRAINT fk_autorizacion_datos_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

-- Relación voluntaria de un Usuario con su profesional de la salud y su autorización para compartir avance.
CREATE TABLE vinculo (
    id_vinculo                BIGINT GENERATED ALWAYS AS IDENTITY,
    id_usuario                UUID NOT NULL,
    id_profesional            UUID NOT NULL,
    autoriza_compartir        BOOLEAN DEFAULT FALSE NOT NULL,
    fecha_inicio              TIMESTAMPTZ DEFAULT now() NOT NULL,
    fecha_fin                 TIMESTAMPTZ,
    CONSTRAINT pk_vinculo PRIMARY KEY (id_vinculo),
    CONSTRAINT fk_vinculo_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_vinculo_profesional FOREIGN KEY (id_profesional) REFERENCES usuario (id_usuario),
    CONSTRAINT ck_vinculo_1 CHECK (id_usuario <> id_profesional)
);

-- Registro de auditoría de acciones sobre datos sensibles.
CREATE TABLE bitacora_cambios (
    id_bitacora               BIGINT GENERATED ALWAYS AS IDENTITY,
    id_usuario                UUID NOT NULL,
    entidad                   VARCHAR(40) NOT NULL,
    id_entidad                VARCHAR(40),
    accion                    VARCHAR(20) NOT NULL,
    detalle                   JSONB,
    fecha                     TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT pk_bitacora_cambios PRIMARY KEY (id_bitacora),
    CONSTRAINT fk_bitacora_cambios_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

-- Conjunto de datos público de procedencia de las imágenes, con licencia y versión.
CREATE TABLE dataset (
    id_dataset                SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre                    VARCHAR(80) NOT NULL UNIQUE,
    fuente_url                TEXT,
    licencia                  VARCHAR(80),
    version                   VARCHAR(20),
    modalidad                 VARCHAR(40),
    CONSTRAINT pk_dataset PRIMARY KEY (id_dataset)
);

-- Caso clínico simulado con su ciclo borrador → revisado → publicado.
CREATE TABLE caso (
    id_caso                   BIGINT GENERATED ALWAYS AS IDENTITY,
    id_autor                  UUID NOT NULL,
    id_revisor                UUID,
    titulo                    VARCHAR(150) NOT NULL,
    tema                      VARCHAR(60) NOT NULL,
    nivel_dificultad          SMALLINT NOT NULL,
    estado                    VARCHAR(10) DEFAULT 'borrador' NOT NULL,
    fuente_clinica            TEXT,
    fecha_publicacion         TIMESTAMPTZ,
    eliminado                 BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT pk_caso PRIMARY KEY (id_caso),
    CONSTRAINT fk_caso_autor FOREIGN KEY (id_autor) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_caso_revisor FOREIGN KEY (id_revisor) REFERENCES usuario (id_usuario),
    CONSTRAINT ck_caso_1 CHECK (estado IN ('borrador','revisado','publicado')),
    CONSTRAINT ck_caso_2 CHECK (nivel_dificultad BETWEEN 1 AND 5),
    CONSTRAINT ck_caso_3 CHECK (id_revisor IS NULL OR id_revisor <> id_autor)
);

-- Etapa ordenada de un caso con la recomendación de la IA definida por el autor.
CREATE TABLE etapa (
    id_etapa                  BIGINT GENERATED ALWAYS AS IDENTITY,
    id_caso                   BIGINT NOT NULL,
    orden                     SMALLINT NOT NULL,
    enunciado                 TEXT NOT NULL,
    recomendacion_ia          TEXT,
    ia_erronea_intencional    BOOLEAN DEFAULT FALSE NOT NULL,
    usa_modelo_vision         BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT pk_etapa PRIMARY KEY (id_etapa),
    CONSTRAINT fk_etapa_caso FOREIGN KEY (id_caso) REFERENCES caso (id_caso) ON DELETE CASCADE,
    CONSTRAINT ck_etapa_1 CHECK (orden >= 1)
);

-- Opciones de respuesta de una etapa; exactamente una es la solución esperada.
CREATE TABLE opcion_decision (
    id_opcion                 BIGINT GENERATED ALWAYS AS IDENTITY,
    id_etapa                  BIGINT NOT NULL,
    texto                     TEXT NOT NULL,
    es_correcta               BOOLEAN NOT NULL,
    retroalimentacion         TEXT,
    CONSTRAINT pk_opcion_decision PRIMARY KEY (id_opcion),
    CONSTRAINT fk_opcion_decision_etapa FOREIGN KEY (id_etapa) REFERENCES etapa (id_etapa) ON DELETE CASCADE
);

-- Imagen o video asociado a una etapa.
CREATE TABLE recurso_multimedia (
    id_recurso                BIGINT GENERATED ALWAYS AS IDENTITY,
    id_etapa                  BIGINT NOT NULL,
    id_dataset                SMALLINT,
    tipo                      VARCHAR(10) NOT NULL,
    ruta_almacenamiento       TEXT NOT NULL,
    licencia                  VARCHAR(80),
    CONSTRAINT pk_recurso_multimedia PRIMARY KEY (id_recurso),
    CONSTRAINT fk_recurso_multimedia_etapa FOREIGN KEY (id_etapa) REFERENCES etapa (id_etapa) ON DELETE CASCADE,
    CONSTRAINT fk_recurso_multimedia_dataset FOREIGN KEY (id_dataset) REFERENCES dataset (id_dataset),
    CONSTRAINT ck_recurso_multimedia_1 CHECK (tipo IN ('imagen','video'))
);

-- Resolución de un caso por un Usuario.
CREATE TABLE intento (
    id_intento                BIGINT GENERATED ALWAYS AS IDENTITY,
    id_usuario                UUID NOT NULL,
    id_caso                   BIGINT NOT NULL,
    aviso_aceptado            BOOLEAN DEFAULT FALSE NOT NULL,
    estado                    VARCHAR(12) DEFAULT 'en_curso' NOT NULL,
    puntaje_total             INTEGER,
    fecha_inicio              TIMESTAMPTZ DEFAULT now() NOT NULL,
    fecha_fin                 TIMESTAMPTZ,
    CONSTRAINT pk_intento PRIMARY KEY (id_intento),
    CONSTRAINT fk_intento_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_intento_caso FOREIGN KEY (id_caso) REFERENCES caso (id_caso),
    CONSTRAINT ck_intento_1 CHECK (estado IN ('en_curso','finalizado','abandonado'))
);

-- Decisión tomada en una etapa con confianza declarada y resultado (RF-007).
CREATE TABLE decision (
    id_decision               BIGINT GENERATED ALWAYS AS IDENTITY,
    id_intento                BIGINT NOT NULL,
    id_etapa                  BIGINT NOT NULL,
    id_opcion                 BIGINT,
    confianza_declarada       SMALLINT NOT NULL,
    siguio_ia                 BOOLEAN NOT NULL,
    es_correcta               BOOLEAN NOT NULL,
    puntaje                   SMALLINT NOT NULL,
    tiempo_respuesta_ms       INTEGER,
    fecha                     TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT pk_decision PRIMARY KEY (id_decision),
    CONSTRAINT fk_decision_intento FOREIGN KEY (id_intento) REFERENCES intento (id_intento) ON DELETE CASCADE,
    CONSTRAINT fk_decision_etapa FOREIGN KEY (id_etapa) REFERENCES etapa (id_etapa) ON DELETE CASCADE,
    CONSTRAINT fk_decision_opcion FOREIGN KEY (id_opcion) REFERENCES opcion_decision (id_opcion),
    CONSTRAINT ck_decision_1 CHECK (confianza_declarada BETWEEN 0 AND 100)
);

-- Cada recomendación o respuesta de la IA con proveedor, versiones y latencia.
CREATE TABLE interaccion_ia (
    id_interaccion            BIGINT GENERATED ALWAYS AS IDENTITY,
    id_intento                BIGINT NOT NULL,
    id_etapa                  BIGINT NOT NULL,
    tipo                      VARCHAR(15) NOT NULL,
    proveedor                 VARCHAR(15) NOT NULL,
    version_modelo            VARCHAR(40) NOT NULL,
    version_prompt            VARCHAR(20),
    consulta                  TEXT NOT NULL,
    respuesta                 TEXT,
    latencia_ms               INTEGER,
    fecha                     TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT pk_interaccion_ia PRIMARY KEY (id_interaccion),
    CONSTRAINT fk_interaccion_ia_intento FOREIGN KEY (id_intento) REFERENCES intento (id_intento) ON DELETE CASCADE,
    CONSTRAINT fk_interaccion_ia_etapa FOREIGN KEY (id_etapa) REFERENCES etapa (id_etapa) ON DELETE CASCADE,
    CONSTRAINT ck_interaccion_ia_1 CHECK (tipo IN ('recomendacion','respuesta')),
    CONSTRAINT ck_interaccion_ia_2 CHECK (proveedor IN ('principal','alternativo','predefinida'))
);

-- Insignias configurables y su criterio de obtención.
CREATE TABLE insignia (
    id_insignia               SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre                    VARCHAR(60) NOT NULL UNIQUE,
    criterio                  TEXT NOT NULL,
    CONSTRAINT pk_insignia PRIMARY KEY (id_insignia)
);

-- Insignias obtenidas por cada usuario.
CREATE TABLE usuario_insignia (
    id_usuario                UUID,
    id_insignia               SMALLINT,
    fecha_obtencion           TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT pk_usuario_insignia PRIMARY KEY (id_usuario, id_insignia),
    CONSTRAINT fk_usuario_insignia_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_insignia_insignia FOREIGN KEY (id_insignia) REFERENCES insignia (id_insignia)
);

-- Imagen propia cargada por el Usuario, almacenada cifrada.
CREATE TABLE estudio_propio (
    id_estudio                BIGINT GENERATED ALWAYS AS IDENTITY,
    id_usuario                UUID NOT NULL,
    id_profesional_compartido UUID,
    ruta_cifrada              TEXT NOT NULL,
    hash_sha256               CHAR(64) NOT NULL,
    desidentificado           BOOLEAN DEFAULT FALSE NOT NULL,
    fecha_carga               TIMESTAMPTZ DEFAULT now() NOT NULL,
    eliminado                 BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT pk_estudio_propio PRIMARY KEY (id_estudio),
    CONSTRAINT fk_estudio_propio_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_estudio_propio_profesional_compartido FOREIGN KEY (id_profesional_compartido) REFERENCES usuario (id_usuario)
);

-- Resultado experimental del modelo de visión sobre un estudio propio.
CREATE TABLE interpretacion_estudio (
    id_interpretacion         BIGINT GENERATED ALWAYS AS IDENTITY,
    id_estudio                BIGINT NOT NULL,
    roi                       JSONB NOT NULL,
    clasificacion             VARCHAR(40) NOT NULL,
    confianza                 NUMERIC(5,2) NOT NULL,
    explicacion               TEXT,
    version_modelo            VARCHAR(40) NOT NULL,
    fecha                     TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT pk_interpretacion_estudio PRIMARY KEY (id_interpretacion),
    CONSTRAINT fk_interpretacion_estudio_estudio FOREIGN KEY (id_estudio) REFERENCES estudio_propio (id_estudio) ON DELETE CASCADE,
    CONSTRAINT ck_interpretacion_estudio_1 CHECK (confianza BETWEEN 0 AND 100)
);

-- Comentario del profesional vinculado sobre un estudio compartido.
CREATE TABLE comentario_estudio (
    id_comentario             BIGINT GENERATED ALWAYS AS IDENTITY,
    id_estudio                BIGINT NOT NULL,
    id_profesional            UUID NOT NULL,
    texto                     TEXT NOT NULL,
    fecha                     TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT pk_comentario_estudio PRIMARY KEY (id_comentario),
    CONSTRAINT fk_comentario_estudio_estudio FOREIGN KEY (id_estudio) REFERENCES estudio_propio (id_estudio) ON DELETE CASCADE,
    CONSTRAINT fk_comentario_estudio_profesional FOREIGN KEY (id_profesional) REFERENCES usuario (id_usuario)
);

-- Restricciones adicionales
CREATE UNIQUE INDEX uq_etapa_orden ON etapa (id_caso, orden);
CREATE UNIQUE INDEX uq_opcion_correcta ON opcion_decision (id_etapa) WHERE es_correcta;
CREATE UNIQUE INDEX uq_decision_etapa ON decision (id_intento, id_etapa);
CREATE UNIQUE INDEX uq_vinculo_activo ON vinculo (id_usuario, id_profesional) WHERE fecha_fin IS NULL;

-- Índices para consultas frecuentes (RNF-001)
CREATE INDEX ix_caso_catalogo ON caso (estado, tema, nivel_dificultad) WHERE NOT eliminado;
CREATE INDEX ix_intento_usuario ON intento (id_usuario, fecha_inicio DESC);
CREATE INDEX ix_decision_intento ON decision (id_intento);
CREATE INDEX ix_interaccion_intento ON interaccion_ia (id_intento, fecha);
CREATE INDEX ix_estudio_usuario ON estudio_propio (id_usuario) WHERE NOT eliminado;
CREATE INDEX ix_bitacora_entidad ON bitacora_cambios (entidad, id_entidad);

-- Vista seudonimizada para exportación (RF-007 7.2): sin nombres ni correos
CREATE VIEW v_exportacion_interaccion AS
SELECT encode(digest(i.id_usuario::text || coalesce(current_setting('app.sal_seudonimo', true), ''), 'sha256'), 'hex') AS id_seudonimo,
       i.id_caso, d.id_etapa, e.ia_erronea_intencional, d.siguio_ia, d.es_correcta, d.confianza_declarada,
       d.tiempo_respuesta_ms, d.puntaje, d.fecha
  FROM decision d JOIN intento i ON i.id_intento = d.id_intento JOIN etapa e ON e.id_etapa = d.id_etapa;

COMMIT;
